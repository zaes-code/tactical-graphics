#!/usr/bin/env node
/**
 * Writes the graphic x field matrix from the registry itself.
 *
 * The registry is the only place that knows which inputs a graphic offers, and it is an
 * exhaustive `Record<TacticalGraphicName, GraphicFieldSet>`, so asking it beats keeping a
 * list by hand: a hand-kept one drifts silently, and a field a graphic ignores looks
 * exactly like one nobody remembered to add.
 *
 * Reads `dist/`, not `src/`, so it reports what a consumer actually gets. Run
 * `npm run build` first.
 *
 *   node scripts/gen-field-matrix.mjs           # writes docs/graphic-field-matrix.{csv,md}
 *   node scripts/gen-field-matrix.mjs --check   # fails if either file is stale
 */
import fs from 'fs';
import path from 'path';
import {fileURLToPath, pathToFileURL} from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const load = rel => import(pathToFileURL(path.join(root, rel)).href);

const {listTacticalGraphicNames, getDisplayName, GRAPHIC_SPECIFICATIONS, GRAPHIC_ENTITY_CODES} = await load('dist/esm/index.js');
const {getGraphicFields} = await load('dist/ol/esm/components/openlayers/index.js');

/** Column order: identity, then annotation, then geometry-ish, then the one-offs. */
const FIELDS = [
    'identifier1',
    'identifier2',
    'countryCodes',
    'additionalInfo',
    'hostility',
    'status',
    'dtg1',
    'dtg2',
    'echelon',
    'direction',
    'mineType',
    'mobility',
    'terrain',
    'altitude1',
    'altitude2',
    'width',
    'length',
    'radius',
    'grids',
    'weapon',
    'rangeFan',
];

const rows = listTacticalGraphicNames()
    .map(name => {
        let fields;
        try {
            fields = getGraphicFields(name);
        } catch {
            return null; // not in the registry: nothing to report
        }
        return {
            name,
            display: getDisplayName(name),
            // An array: a graphic can be defined by both publications. Joined, not
            // left as-is, because the default toString puts a comma in it and that
            // silently shifted every later column of the CSV by one.
            spec: (GRAPHIC_SPECIFICATIONS?.[name] ?? []).join(' + '),
            code: GRAPHIC_ENTITY_CODES?.[name] ?? '',
            fields,
        };
    })
    .filter(Boolean)
    .sort((a, b) => a.display.localeCompare(b.display));

const csv = [
    ['Graphic', 'Enum', 'Specification', 'APP-06 code', ...FIELDS].join(','),
    ...rows.map(r => [`"${r.display}"`, r.name, `"${r.spec}"`, r.code ?? '', ...FIELDS.map(f => (r.fields[f] ? 'Y' : ''))].join(',')),
].join('\n');

const totals = FIELDS.map(f => rows.filter(r => r.fields[f]).length);
const md = [
    '# Graphic x field matrix',
    '',
    `Generated by \`scripts/gen-field-matrix.mjs\` from \`dist/\`. ${rows.length} graphics, ${FIELDS.length} fields.`,
    '',
    'Which inputs the Feature Properties dialog offers per graphic. `Y` means the field is',
    'offered; blank means it is not. Regenerate after touching `graphicFieldRegistry.ts`.',
    '',
    `| Graphic | Spec | Code | ${FIELDS.join(' | ')} |`,
    `| --- | --- | --- | ${FIELDS.map(() => '---').join(' | ')} |`,
    ...rows.map(r => `| ${r.display} | ${r.spec} | ${r.code ?? ''} | ${FIELDS.map(f => (r.fields[f] ? 'Y' : '')).join(' | ')} |`),
    '',
    `| **Totals** | | | ${totals.join(' | ')} |`,
    '',
].join('\n');

const targets = [
    [path.join(root, 'docs', 'graphic-field-matrix.csv'), csv],
    [path.join(root, 'docs', 'graphic-field-matrix.md'), md],
];

if (process.argv.includes('--check')) {
    const stale = targets.filter(([file, want]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== want);
    if (stale.length) {
        console.error(`stale, run: node scripts/gen-field-matrix.mjs\n  ${stale.map(([f]) => path.relative(root, f)).join('\n  ')}`);
        process.exit(1);
    }
    console.log(`up to date: ${rows.length} graphics`);
} else {
    for (const [file, content] of targets) {
        fs.writeFileSync(file, content);
        console.log(`  wrote ${path.relative(root, file)}`);
    }
    console.log(`${rows.length} graphics, ${FIELDS.length} fields`);
}
